/** Injects the current date/time so Ares reasons about "heute"/"morgen" correctly instead of guessing. */
export function buildSystemPrompt(): string {
  const now = new Date();
  const formatter = new Intl.DateTimeFormat("de-DE", {
    timeZone: "Europe/Berlin",
    weekday: "long",
    year: "numeric",
    month: "long",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
  const context = `Heute ist ${formatter.format(now)} (Europe/Berlin). Nutze dieses Datum für alle relativen Zeitangaben wie "heute", "morgen" oder Kalenderzeiträume.`;
  return ARES_SYSTEM_PROMPT.replace("{{DYNAMIC_CONTEXT}}", context);
}
